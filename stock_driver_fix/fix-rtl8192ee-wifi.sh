#!/bin/bash
# fix-rtl8192ee-wifi.sh
#
# Makes a Realtek RTL8192EE PCIe wifi card (and its rtlwifi siblings RTL8723BE,
# RTL8821AE, RTL8188EE) stable on Linux Mint / Ubuntu with the STOCK in-kernel
# driver. Written 2026-10-22 after fixing a ThinkPad X240 on Mint 22.3 / kernel 6.8.
#
# Symptom it fixes: wifi works for seconds to minutes after boot, then dies;
# dmesg repeats "rtl8192ee: Init MAC failed"; the card's PCI config space reads
# 0xff; only a full power-off brings it back.
#
# What it does (persistent, idempotent, safe to re-run):
#   1. driver power management off  -> /etc/modprobe.d/<driver>.conf
#   2. NetworkManager wifi powersave off -> /etc/NetworkManager/conf.d/
#   3. boot service that clears PCIe ASPM L1 + L1 substates on the card's root
#      port and the card (the real cause of the hang), re-applied after suspend
#   4. clears any saved rfkill soft block on wlan
#   5. reports the state and tells you whether a full power-off is needed
#
# Usage:  sudo ./fix-rtl8192ee-wifi.sh
# Afterwards: reboot (full power-off if the card already hung). Then check
# after ten minutes that `dmesg | grep -c "Init MAC failed"` prints 0.
set -u

[ "$(id -u)" -eq 0 ] || { echo "Run with sudo: sudo $0"; exit 1; }
for t in lspci setpci modinfo systemctl; do
	command -v "$t" >/dev/null || { echo "missing tool: $t (apt install pciutils kmod)"; exit 1; }
done

# ---- 1. find the card and its driver ---------------------------------------
declare -A MOD=( [10ec:818b]=rtl8192ee [10ec:b723]=rtl8723be [10ec:8821]=rtl8821ae [10ec:8179]=rtl8188ee )
CARD=""; MODULE=""; PCIID=""
for id in "${!MOD[@]}"; do
	addr=$(lspci -Dn -d "$id" 2>/dev/null | awk '{print $1}' | head -1)
	if [ -n "$addr" ]; then CARD=$addr; MODULE=${MOD[$id]}; PCIID=$id; break; fi
done
if [ -z "$CARD" ]; then
	echo "No supported Realtek PCIe wifi card found. Output of lspci:"; lspci -nn | grep -i -E "network|wireless"
	exit 1
fi
RP=$(basename "$(dirname "$(readlink -f /sys/bus/pci/devices/$CARD)")")
echo "card: $CARD [$PCIID]  driver: $MODULE  root port: $RP"

# ---- 2. driver power management off ----------------------------------------
opts=""
for p in ips swlps fwlps aspm; do
	modinfo -p "$MODULE" 2>/dev/null | grep -q "^$p:" && opts="$opts $p=0"
done
cat > "/etc/modprobe.d/$MODULE.conf" <<CONF
# Realtek $MODULE: disable the driver's power management.
# (generated by fix-rtl8192ee-wifi.sh)
#   ips=0   never power the NIC off when idle (inactive power save)
#   fwlps=0 / swlps=0  no firmware / software leisure power save
#   aspm=0  the driver does not enable PCIe ASPM on the link
# With the defaults the card hangs and logs "$MODULE: Init MAC failed".
options $MODULE$opts
CONF
echo "wrote /etc/modprobe.d/$MODULE.conf  (options $MODULE$opts)"
if command -v lsinitramfs >/dev/null && lsinitramfs "/boot/initrd.img-$(uname -r)" 2>/dev/null | grep -q "$MODULE.ko"; then
	echo "module is in the initramfs, updating it"; update-initramfs -u
fi

# ---- 3. NetworkManager wifi power saving off --------------------------------
mkdir -p /etc/NetworkManager/conf.d
cat > /etc/NetworkManager/conf.d/wifi-powersave-off.conf <<'CONF'
# Disable 802.11 power saving on wifi connections (Realtek rtlwifi stability).
[connection]
wifi.powersave = 2
CONF
command -v nmcli >/dev/null && nmcli general reload conf 2>/dev/null
echo "wrote /etc/NetworkManager/conf.d/wifi-powersave-off.conf"

# ---- 4. boot-time ASPM L1 disable on the root port and card ----------------
cat > /usr/local/sbin/rtl8192ee-noaspm <<'SCRIPT'
#!/bin/bash
# Keep a Realtek PCIe wifi card's link out of ASPM L1 / L1 substates.
# The card drops off the bus once the link idles into L1: the BIOS enables L1
# on the root port, the firmware denies the kernel control of ASPM, and the
# driver's hardware init makes the card request L1. Refusing L1 on the root
# port (and clearing it on the card) prevents the hang.
CARD=""
for id in 10ec:818b 10ec:b723 10ec:8821 10ec:8179; do
	CARD=$(lspci -Dn -d "$id" 2>/dev/null | awk '{print $1}' | head -1)
	[ -n "$CARD" ] && break
done
[ -n "$CARD" ] || { echo "no Realtek wifi card found"; exit 0; }
RP=$(basename "$(dirname "$(readlink -f /sys/bus/pci/devices/$CARD)")")
RP=${RP#0000:}; DEV=${CARD#0000:}

# root port Link Control: ASPM bits [1:0] = 0 (no L0s, no L1)
v=$(setpci -s "$RP" CAP_EXP+0x10.w) || { echo "cannot read root port $RP"; exit 1; }
setpci -s "$RP" CAP_EXP+0x10.w=$(printf '%04x' $(( 0x$v & ~0x3 )))
# root port L1 PM Substates Control 1: clear the four enable bits
off=$(lspci -s "$RP" -vv 2>/dev/null | sed -n 's/.*Capabilities: \[\([0-9a-f]*\) v[0-9]*\] L1 PM Substates.*/\1/p')
c=""
if [ -n "$off" ]; then
	c=$(setpci -s "$RP" "0x$off+0x8.l")
	setpci -s "$RP" "0x$off+0x8.l=$(printf '%08x' $(( 0x$c & ~0xf )))"
fi
# card Link Control: ASPM bits [1:0] = 0, Clock PM enable (bit 8) = 0
d=$(setpci -s "$DEV" CAP_EXP+0x10.w 2>/dev/null)
case "$d" in
	""|ffff) echo "card $DEV not readable (off the bus: a full power-off is needed)" ;;
	*) setpci -s "$DEV" CAP_EXP+0x10.w=$(printf '%04x' $(( 0x$d & ~0x103 ))) ;;
esac
echo "done: root port $RP LnkCtl $v -> $(setpci -s "$RP" CAP_EXP+0x10.w), L1SubCtl1 ${c:-n/a} -> $( [ -n "$off" ] && setpci -s "$RP" "0x$off+0x8.l" ), card $DEV LnkCtl ${d:-n/a} -> $(setpci -s "$DEV" CAP_EXP+0x10.w 2>/dev/null || echo n/a)"
SCRIPT
chmod 755 /usr/local/sbin/rtl8192ee-noaspm

cat > /etc/systemd/system/rtl8192ee-noaspm.service <<'UNIT'
[Unit]
Description=Disable PCIe ASPM on the Realtek wifi link (card drops off the bus otherwise)
DefaultDependencies=no
After=sysinit.target
Before=network-pre.target NetworkManager.service
Wants=network-pre.target

[Service]
Type=oneshot
ExecStart=/usr/local/sbin/rtl8192ee-noaspm
RemainAfterExit=yes

[Install]
WantedBy=multi-user.target
UNIT

mkdir -p /usr/lib/systemd/system-sleep
cat > /usr/lib/systemd/system-sleep/rtl8192ee-noaspm <<'HOOK'
#!/bin/sh
# Re-apply the ASPM workaround after resume; firmware may re-enable L1.
[ "$1" = "post" ] && /usr/local/sbin/rtl8192ee-noaspm
exit 0
HOOK
chmod 755 /usr/lib/systemd/system-sleep/rtl8192ee-noaspm

systemctl daemon-reload
systemctl enable rtl8192ee-noaspm.service >/dev/null 2>&1
systemctl restart rtl8192ee-noaspm.service
echo "installed and started rtl8192ee-noaspm.service ($(systemctl is-enabled rtl8192ee-noaspm.service), $(systemctl is-active rtl8192ee-noaspm.service))"

# ---- 5. rfkill: clear a soft block that would otherwise persist across boots
command -v rfkill >/dev/null && rfkill unblock wlan 2>/dev/null
for f in /var/lib/systemd/rfkill/*:wlan; do [ -f "$f" ] && echo 0 > "$f"; done

# ---- 6. report --------------------------------------------------------------
echo
echo "=== result ==="
echo "root port $RP: $(lspci -vvv -s "${RP#0000:}" 2>/dev/null | grep 'LnkCtl:' | sed 's/^[[:space:]]*//')"
if lspci -vvv -s "${CARD#0000:}" 2>/dev/null | grep -q "Unknown header"; then
	echo "card $CARD: NOT responding on the PCIe bus (it hung before this fix ran)."
	echo "  -> Shut down fully (not Restart), wait 10 seconds, power on. The fix is in place for the next boot."
else
	echo "card $CARD: responding, $(lspci -vvv -s "${CARD#0000:}" 2>/dev/null | grep 'LnkCtl:' | sed 's/^[[:space:]]*//')"
fi
if [ -d "/sys/module/$MODULE" ]; then
	cur=""; for p in $opts; do n=${p%=0}; cur="$cur $n=$(cat "/sys/module/$MODULE/parameters/$n" 2>/dev/null)"; done
	echo "$MODULE currently loaded with:$cur   (N or 0 = off; the new options apply on the next boot)"
else
	echo "$MODULE is not loaded; the options apply when it loads"
fi
echo
echo "Next: reboot (full power-off if the card hung). After ten minutes check:"
echo "  dmesg | grep -c 'Init MAC failed'      # must print 0"
echo "  systemctl status rtl8192ee-noaspm      # active (exited), LnkCtl ... -> 0040"
